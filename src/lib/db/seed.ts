async function seed() {
  console.log('🌱 开始执行种子脚本...\n');

  if (!process.env.DATABASE_URL) {
    console.error('❌ 错误:找不到 DATABASE_URL 环境变量');
    console.error('   请确认 .env.local 文件存在且包含 DATABASE_URL');
    process.exit(1);
  }

  const sql = neon(process.env.DATABASE_URL);
  const db = drizzle(sql);

  try {
    // 检查表里是否已有数据
    const existing = await db.select().from(characters);

    if (existing.length > 0) {
      console.log(`ℹ️  characters 表已有 ${existing.length} 条数据,跳过插入`);
      console.log('   现有角色:', existing.map((c) => c.name).join(', '));
      console.log('\n💡 如果想重新插入,请先在 Neon 控制台清空 characters 表');
      return;
    }

    // 插入 4 个角色
    console.log('📝 插入 4 个预设角色...\n');

    for (const char of CHARACTERS_DATA) {
      await db.insert(characters).values(char);
      console.log(`   ✓ ${char.name}(${char.description})`);
    }

    console.log('\n✅ 种子数据插入完成!');
    console.log(`   共插入 ${CHARACTERS_DATA.length} 个角色`);
    console.log('\n💡 下一步:刷新角色选择页应该能看到 4 张卡片');
    console.log('💡 提示:如果图片显示不出来,记得把图片放到 public/characters/ 对应目录');
  } catch (error) {
    console.error('❌ 插入失败:', error);
    process.exit(1);
  }
}

seed();
